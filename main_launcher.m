function main_launcher()
    % 信号处理工具统一启动器
    % 版本: 1.0
    % 特性: 模块化、可扩展、配置文件驱动
    
    % 自动初始化路径
    try
        init_project();
    catch ME
        errordlg(['路径初始化失败: ' ME.message], '初始化错误');
        return;
    end
    
    % 创建主窗口
    launcher_fig = figure('Name', 'Signal Processing Tool', ...
                         'Position', [300, 150, 900, 650], ...
                         'MenuBar', 'none', 'ToolBar', 'none', ...
                         'NumberTitle', 'off', 'Resize', 'off', ...
                         'Color', [0.95 0.95 0.95]);
    
    % 加载模块配置
    modules = load_module_config();
    
    % 创建UI
    create_ui(launcher_fig, modules);
end

