function create_ui(fig, modules)
    % 创建用户界面
    
    % === 顶部标题栏 ===
    title_panel = uipanel('Parent', fig, ...
                         'Position', [0.02 0.88 0.96 0.10], ...
                         'BackgroundColor', [0.15 0.25 0.45], ...
                         'BorderType', 'none');
    
    % 主标题
    uicontrol('Parent', title_panel, 'Style', 'text', ...
              'String', 'Signal Processing Tool', ...
              'Position', [20, 30, 400, 35], ...
              'FontSize', 24, 'FontWeight', 'bold', ...
              'ForegroundColor', [1 1 1], ...
              'BackgroundColor', [0.15 0.25 0.45], ...
              'HorizontalAlignment', 'left');
    
    % 副标题
    uicontrol('Parent', title_panel, 'Style', 'text', ...
              'String', 'Ultrasonic Signal Analysis Platform', ...
              'Position', [20, 10, 300, 20], ...
              'FontSize', 11, 'FontAngle', 'italic', ...
              'ForegroundColor', [0.8 0.85 0.95], ...
              'BackgroundColor', [0.15 0.25 0.45], ...
              'HorizontalAlignment', 'left');
    
    % 版本信息
    uicontrol('Parent', title_panel, 'Style', 'text', ...
              'String', 'v2.0', ...
              'Position', [800, 30, 60, 25], ...
              'FontSize', 12, ...
              'ForegroundColor', [0.7 0.8 0.9], ...
              'BackgroundColor', [0.15 0.25 0.45]);
    
    % === 模块选择区域 ===
    modules_panel = uipanel('Parent', fig, ...
                           'Position', [0.02 0.30 0.96 0.56], ...
                           'Title', 'Select Analysis Module', ...
                           'FontSize', 13, 'FontWeight', 'bold', ...
                           'BackgroundColor', [0.95 0.95 0.95]);
    
    % 修复: 动态创建模块按钮 - 确保按钮正确创建
    num_modules = length(modules);
    cols = 3;  % 每行3个模块
    rows = ceil(num_modules / cols);
    
    button_width = 260;
    button_height = 140;
    spacing_h = 30;
    spacing_v = 30;
    
    % 计算起始位置（居中对齐）
    total_width = cols * button_width + (cols-1) * spacing_h;
    start_x = (900 * 0.96 - total_width) / 2;
    
    % 从上往下布局
    panel_height = 650 * 0.56;
    start_y = panel_height - button_height - 40;
    
    for i = 1:num_modules
        row = floor((i - 1) / cols);
        col = mod(i - 1, cols);
        
        x = start_x + col * (button_width + spacing_h);
        y = start_y - row * (button_height + spacing_v);
        
        create_module_button(modules_panel, modules(i), x, y, button_width, button_height);
    end
    
    % === 底部信息栏 ===
    info_panel = uipanel('Parent', fig, ...
                        'Position', [0.02 0.12 0.96 0.16], ...
                        'Title', 'Quick Start Guide', ...
                        'FontSize', 12, 'FontWeight', 'bold', ...
                        'BackgroundColor', [0.95 0.95 0.95]);
    
    guide_text = sprintf(['Welcome to Signal Processing Tool!\n\n' ...
                         '1. Select a module above to begin analysis\n' ...
                         '2. Each module is optimized for specific data types\n' ...
                         '3. All modules share the same core analysis engine\n' ...
                         '4. Use Settings to customize default parameters']);
    
    uicontrol('Parent', info_panel, 'Style', 'text', ...
              'String', guide_text, ...
              'Position', [20, 10, 600, 75], ...
              'FontSize', 10, ...
              'HorizontalAlignment', 'left', ...
              'BackgroundColor', [0.95 0.95 0.95]);
    
    % === 底部按钮区域 ===
    button_panel = uipanel('Parent', fig, ...
                          'Position', [0.02 0.02 0.96 0.08], ...
                          'BorderType', 'none', ...
                          'BackgroundColor', [0.95 0.95 0.95]);
    
    % 设置按钮
    uicontrol('Parent', button_panel, 'Style', 'pushbutton', ...
              'String', '⚙ Settings', ...
              'Position', [20, 10, 120, 35], ...
              'FontSize', 11, ...
              'BackgroundColor', [0.9 0.9 0.9], ...
              'Callback', @open_settings);
    
    % 帮助按钮
    uicontrol('Parent', button_panel, 'Style', 'pushbutton', ...
              'String', '? Help', ...
              'Position', [150, 10, 120, 35], ...
              'FontSize', 11, ...
              'BackgroundColor', [0.9 0.9 0.9], ...
              'Callback', @open_help);
    
    % 关于按钮
    uicontrol('Parent', button_panel, 'Style', 'pushbutton', ...
              'String', 'ⓘ About', ...
              'Position', [280, 10, 120, 35], ...
              'FontSize', 11, ...
              'BackgroundColor', [0.9 0.9 0.9], ...
              'Callback', @show_about);
    
    % 退出按钮
    uicontrol('Parent', button_panel, 'Style', 'pushbutton', ...
              'String', 'Exit', ...
              'Position', [760, 10, 100, 35], ...
              'FontSize', 11, ...
              'BackgroundColor', [1.0 0.85 0.85], ...
              'Callback', @(~,~) close(fig));
end

function create_module_button(parent, module, x, y, width, height)
    % 创建单个模块按钮
    
    % 创建按钮面板
    btn_panel = uipanel('Parent', parent, ...
                       'Units', 'pixels', ...  % 修复: 使用像素单位
                       'Position', [x, y, width, height], ...
                       'BackgroundColor', [1 1 1], ...
                       'BorderType', 'line', ...
                       'HighlightColor', module.icon_color, ...
                       'BorderWidth', 2);
    
    % 模块图标区域（顶部色块）
    icon_height = height * 0.35;
    icon_panel = uipanel('Parent', btn_panel, ...
                        'Units', 'pixels', ...
                        'Position', [0, height - icon_height, width, icon_height], ...
                        'BackgroundColor', module.icon_color, ...
                        'BorderType', 'none');
    
    % 模块名称（大号）
    uicontrol('Parent', icon_panel, 'Style', 'text', ...
              'String', module.name, ...
              'Units', 'pixels', ...
              'Position', [10, 15, width-20, 30], ...
              'FontSize', 18, 'FontWeight', 'bold', ...
              'ForegroundColor', [1 1 1], ...
              'BackgroundColor', module.icon_color, ...
              'HorizontalAlignment', 'center');
    
    % 全名标题
    uicontrol('Parent', btn_panel, 'Style', 'text', ...
              'String', module.full_name, ...
              'Units', 'pixels', ...
              'Position', [10, height - icon_height - 25, width-20, 20], ...
              'FontSize', 11, 'FontWeight', 'bold', ...
              'HorizontalAlignment', 'center', ...
              'BackgroundColor', [1 1 1]);
    
    % 功能描述
    uicontrol('Parent', btn_panel, 'Style', 'text', ...
              'String', module.description, ...
              'Units', 'pixels', ...
              'Position', [10, 40, width-20, 50], ...
              'FontSize', 9, ...
              'HorizontalAlignment', 'left', ...
              'BackgroundColor', [1 1 1]);
    
    % 启动按钮
    if module.enabled
        btn_color = module.icon_color;
        btn_text = 'Launch';
        btn_callback = module.callback;
    else
        btn_color = [0.7 0.7 0.7];
        btn_text = 'Coming Soon';
        btn_callback = @(~,~) msgbox('This module is under development', 'Info');
    end
    
    uicontrol('Parent', btn_panel, 'Style', 'pushbutton', ...
              'String', btn_text, ...
              'Units', 'pixels', ...
              'Position', [width/2-50, 5, 100, 30], ...
              'FontSize', 10, 'FontWeight', 'bold', ...
              'BackgroundColor', btn_color, ...
              'ForegroundColor', [1 1 1], ...
              'Callback', btn_callback);
end

